"""Multi-framework test suite emitters (Pytest, Playwright, Kotlin JUnit 5, Gherkin, Markdown, JSON)."""

from __future__ import annotations

import json
import re
from typing import Any

from pairspec.ipog import GenerationResult


def _slug(name: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9]+", "_", name).strip("_").lower()
    if cleaned[:1].isdigit():
        cleaned = f"spec_{cleaned}"  # must stay a valid identifier (`invoke_<slug>`)
    return cleaned or "spec"


def _pascal(name: str) -> str:
    parts = [p for p in re.split(r"[^a-zA-Z0-9]+", name) if p]
    return "".join(p[:1].upper() + p[1:] for p in parts) or "Spec"


def emit_suite(result: GenerationResult, fmt: str) -> str:
    """Emit a traceable test suite or report from a GenerationResult."""
    key = fmt.strip().lower()
    if key == "pytest":
        return _emit_pytest(result)
    if key == "playwright":
        return _emit_playwright(result)
    if key == "kotlin":
        return _emit_kotlin(result)
    if key == "gherkin":
        return _emit_gherkin(result)
    if key in ("md", "markdown"):
        return _emit_markdown(result)
    if key == "json":
        return json.dumps(result.to_dict(), indent=2, ensure_ascii=False) + "\n"
    raise ValueError(f"Unsupported emitter format: {fmt!r} (expected: pytest, playwright, kotlin, gherkin, markdown, json)")


def _emit_pytest(result: GenerationResult) -> str:
    slug = _slug(result.spec_name)
    lines = [
        f'"""Blind combinatorial test suite generated by PairSpec for `{result.spec_name}` (v{result.spec_version}).',
        f"Spec fingerprint: {result.spec_fingerprint} | Strength: t={result.strength} | "
        f"{len(result.cases)} cases (vs {result.cartesian_size} cartesian, -{result.reduction_pct}%).",
        '"""',
        "from __future__ import annotations",
        "",
        "import pytest",
        "",
        "# Wire your System Under Test (SUT) adapter here without leaking SUT logic into the spec oracle:",
        f"def invoke_{slug}(inputs: dict) -> dict:",
        f'    raise NotImplementedError("Connect `{slug}` SUT adapter before running tests")',
        "",
    ]

    for case in result.cases:
        fn_suffix = case.case_id.lower().replace("-", "_")
        rules_note = ", ".join(case.matched_oracles) if case.matched_oracles else "default"
        lines.extend(
            [
                f"# @pairspec:{case.case_id} | oracles: {rules_note}",
                f"def test_{slug}_{fn_suffix}() -> None:",
                f"    inputs = {case.inputs!r}",
                f"    expected = {case.expected!r}",
                f"    actual = invoke_{slug}(inputs)",
                "    for key, exp_val in expected.items():",
                '        assert actual.get(key) == exp_val, f"{key}: expected {exp_val!r}, got {actual.get(key)!r}"',
                "",
            ]
        )
    return "\n".join(lines)


def _emit_playwright(result: GenerationResult) -> str:
    slug = _slug(result.spec_name)
    lines = [
        f"// Blind combinatorial test suite generated by PairSpec for `{result.spec_name}` (v{result.spec_version})",
        f"// Spec fingerprint: {result.spec_fingerprint} | Strength: t={result.strength} | {len(result.cases)} cases",
        "import { test, expect } from '@playwright/test';",
        "",
        "async function executeScenario(inputs: Record<string, unknown>): Promise<Record<string, unknown>> {",
        f"  throw new Error('Connect Playwright/API adapter for {slug} before running');",
        "}",
        "",
        f"test.describe('{result.spec_name} (PairSpec t={result.strength})', () => {{",
    ]

    for case in result.cases:
        rules_note = ", ".join(case.matched_oracles) if case.matched_oracles else "default"
        inputs_json = json.dumps(case.inputs, ensure_ascii=False)
        expected_json = json.dumps(case.expected, ensure_ascii=False)
        lines.extend(
            [
                f"  // @pairspec:{case.case_id} | oracles: {rules_note}",
                f"  test('@pairspec:{case.case_id} [{rules_note}]', async () => {{",
                f"    const inputs = {inputs_json};",
                f"    const expected = {expected_json};",
                "    const actual = await executeScenario(inputs);",
                "    for (const [key, value] of Object.entries(expected)) {",
                "      expect(actual[key], `Mismatch on ${key}`).toEqual(value);",
                "    }",
                "  });",
                "",
            ]
        )
    lines.append("});")
    lines.append("")
    return "\n".join(lines)


def _kt_literal(val: Any) -> str:
    if val is None:
        return "null"
    if isinstance(val, bool):
        return "true" if val else "false"
    if isinstance(val, (int, float)):
        return str(val)
    return _kt_string(str(val))


def _kt_string(text: str) -> str:
    # `$` starts a string template in Kotlin and must be escaped like quotes and backslashes.
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    return f'"{escaped}"'


def _kt_map(mapping: dict[str, Any]) -> str:
    if not mapping:
        return "emptyMap()"
    entries = ", ".join(f"{_kt_string(str(k))} to {_kt_literal(v)}" for k, v in mapping.items())
    return f"mapOf({entries})"


def _emit_kotlin(result: GenerationResult) -> str:
    cls_name = f"{_pascal(result.spec_name)}PairSpecTest"
    lines = [
        f"// Blind combinatorial JUnit 5 suite generated by PairSpec for `{result.spec_name}` (v{result.spec_version})",
        f"// Spec fingerprint: {result.spec_fingerprint} | Strength: t={result.strength} | {len(result.cases)} cases",
        "import org.junit.jupiter.api.Assertions.assertEquals",
        "import org.junit.jupiter.api.Test",
        "",
        f"class {cls_name} {{",
        "",
        "    private fun invokeSut(inputs: Map<String, Any?>): Map<String, Any?> {",
        f"        TODO({_kt_string('Connect Kotlin SUT adapter for ' + result.spec_name)})",
        "    }",
        "",
    ]

    for case in result.cases:
        fn_suffix = case.case_id.replace("-", "_")
        rules_note = ", ".join(case.matched_oracles) if case.matched_oracles else "default"
        lines.extend(
            [
                f"    // @pairspec:{case.case_id} | oracles: {rules_note}",
                "    @Test",
                f"    fun `case {fn_suffix}`() {{",
                f"        val inputs = {_kt_map(case.inputs)}",
                f"        val expected = {_kt_map(case.expected)}",
                "        val actual = invokeSut(inputs)",
                "        expected.forEach { (key, expVal) ->",
                '            assertEquals(expVal, actual[key], "Mismatch on key=$key")',
                "        }",
                "    }",
                "",
            ]
        )
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _emit_gherkin(result: GenerationResult) -> str:
    lines = [
        f"# Spec fingerprint: {result.spec_fingerprint} | Strength: t={result.strength} | {len(result.cases)} cases",
        f"Feature: {result.spec_name} (PairSpec blind combinatorial suite)",
        "",
    ]
    for case in result.cases:
        rules_note = ", ".join(case.matched_oracles) if case.matched_oracles else "default"
        lines.append(f"  @pairspec:{case.case_id}")
        lines.append(f"  Scenario: {case.case_id} ({rules_note})")
        for idx, (k, v) in enumerate(case.inputs.items()):
            kw = "Given" if idx == 0 else "And"
            lines.append(f"    {kw} parameter \"{k}\" is {json.dumps(v, ensure_ascii=False)}")
        lines.append(f"    When \"{result.spec_name}\" is evaluated")
        if case.expected:
            for idx, (k, v) in enumerate(case.expected.items()):
                kw = "Then" if idx == 0 else "And"
                lines.append(f"    {kw} expected \"{k}\" should be {json.dumps(v, ensure_ascii=False)}")
        else:
            lines.append("    Then the operation completes according to spec")
        lines.append("")
    return "\n".join(lines)


def _emit_markdown(result: GenerationResult) -> str:
    param_cols = list(result.parameter_domains.keys())
    lines = [
        f"# PairSpec Matrix — `{result.spec_name}` (v{result.spec_version})",
        "",
        f"- **Fingerprint**: `{result.spec_fingerprint}`",
        f"- **Combinatorial strength**: `t={result.strength}`",
        f"- **Matrix size**: `{len(result.cases)}` cases (vs `{result.cartesian_size}` cartesian, **-{result.reduction_pct}%**"
        f", incl. `{result.oracle_unmask_cases}` oracle-unmasking cases)",
        f"- **Verified t-wise coverage**: `{result.coverage.coverage_pct}%` "
        f"({result.coverage.covered_tuples}/{result.coverage.total_feasible_tuples} feasible tuples, "
        f"`{result.coverage.exclusion_violations}` exclusion violations)",
        "",
    ]
    headers = ["ID"] + param_cols + ["Expected (Blind Oracle)", "Rules"]
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("|" + "|".join(["---"] * len(headers)) + "|")
    for case in result.cases:
        row = [f"`@pairspec:{case.case_id}`"]
        for p in param_cols:
            row.append(f"`{case.inputs[p]!r}`")
        exp_str = ", ".join(f"{k}={v!r}" for k, v in case.expected.items()) if case.expected else "-"
        rules_str = ", ".join(case.matched_oracles) if case.matched_oracles else "default"
        row.append(exp_str.replace("|", "\\|"))
        row.append(rules_str.replace("|", "\\|"))
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    return "\n".join(lines)
